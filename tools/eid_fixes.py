def pieces(kind, s):
    """The words of a stored string split from the markers around them.

    Conditional lines (section 12) start with a type letter - 'S' for a line,
    'T' and then 's'/'n' before each piece of a table - glued to the first word,
    so a whole-word match would never see that word's start. The markers are
    kept apart and put back exactly as they were."""
    out = []
    for i, chunk in enumerate(s.split('\x1f')):
        head = 0
        if kind == 12:
            if i == 0 and chunk[:1] == 'T':
                head = 2
            elif chunk[:1] in ('S', 's', 'n'):
                head = 1
        out.append((chunk[:head], chunk[head:]))
    return out


def mend(kind, s, typos):
    """s with every typo of the list put right."""
    if not typos:
        return s
    out = []
    for head, body in pieces(kind, s):
        for _, wrong, right, word, _, _ in typos:
            if word:
                body = re.sub(r'(?<!\w)' + re.escape(wrong) + r'(?!\w)', lambda m: right, body)
            else:
                body = body.replace(wrong, right)
        out.append(head + body)
    return '\x1f'.join(out)


def text_at(pool, off):
    end = pool.index(b'\0', off)
    return pool[off:end].decode('utf-8')


def main(target):
    blocks, pool, version = read_bin(target)
    added = {}
    changed = 0
    for code, sections in blocks:
        mine = [f for f in FIXES if f[0] == code]
        typos = [t for t in TYPOS if t[0] == code]
        ours = dict(((k, i), (en, said)) for c, k, i, en, said in OURS if c == code)
        if not mine and not typos and not ours:
            continue
        for s, (kind, rows) in enumerate(sections):
            for r, (ident, name, text) in enumerate(rows):
                new_name, new_text = name, text
                for which in ('name', 'text'):
                    off = new_name if which == 'name' else new_text
                    was = text_at(pool, off)
                    now = was
                    if which == 'text' and (kind, ident) in ours and was == ours[(kind, ident)][0]:
                        now = ours[(kind, ident)][1]
                    for _, wrong, right, _ in mine:
                        now = now.replace(wrong, right)
                    now = mend(kind, now, typos)
                    if now == was:
                        continue
                    if now not in added:
                        added[now] = len(pool)
                        pool += now.encode('utf-8') + b'\0'
                    if which == 'name':
                        new_name = added[now]
                    else:
                        new_text = added[now]
                    changed += 1
                rows[r] = (ident, new_name, new_text)
    write_bin(target, blocks, pool, version)
    print('%s: %d texts mended, %d new strings' % (target, changed, len(added)))


