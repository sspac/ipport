# -*- coding: utf-8 -*-
"""Where the art of each trinket lies inside its 32x32 picture -> cpp/trinket_art.h.

The twins' drop button (twintrinkets.c) centres every trinket by its ART, not by
its box: the art is 13..30 units across and often off-centre (Bloody Penny lies
along the bottom of its picture). The game's own RenderTrinket draws by the box,
so the bounding box of the opaque texels is baked here, once, from the same art
the game loads.

The editions are layered the way the game layers them: Repentance first, then
Afterbirth+, Afterbirth and Rebirth for anything it does not carry itself.
Monkey Paw (20) is a strip of four 32x32 frames; its box is the union of the four.

    py -3 tools/trinket_art.py
"""
import glob
import os
import re

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, 'work', 'app')
EDITIONS = ["repentance-resources", "afterbirthplus-resources", "afterbirth-resources", "rebirth-resources"]
OUT = os.path.join(ROOT, 'port', 'app', 'src', 'main', 'cpp', 'trinket_art.h')


def find_art():
    found = {}
    for ed in EDITIONS:
        for f in glob.glob(os.path.join(APP, ed, "data", "gfx", "items", "trinkets", "trinket_*.png")):
            m = re.match(r"trinket_(\d+)_", os.path.basename(f))
            if not m:
                continue
            tid = int(m.group(1))
            found.setdefault(tid, f)
    return found


def art_box(path):
    im = Image.open(path).convert("RGBA")
    box = None
    for fx in range(0, max(im.width, 32), 32):
        frame = im.crop((fx, 0, fx + 32, 32))
        bb = frame.getchannel("A").point(lambda v: 255 if v > 0 else 0).getbbox()
        if not bb:
            continue
        box = bb if box is None else (min(box[0], bb[0]), min(box[1], bb[1]),
                                      max(box[2], bb[2]), max(box[3], bb[3]))
    return box or (0, 0, 32, 32)


def main():
    art = find_art()
    top = max(art)
    lines = [
        "/* Generated by tools/trinket_art.py - do not edit by hand. */",
        "/*",
        " * The opaque texels of each trinket's 32x32 picture: x0, y0, x1, y1 (x1, y1",
        " * one past the end). Index is the trinket id; a missing one is the whole box.",
        " */",
        "#define TRINKET_ART_MAX %d" % (top + 1),
        "static const unsigned char TRINKET_ART[TRINKET_ART_MAX][4] = {",
    ]
    for tid in range(top + 1):
        b = art_box(art[tid]) if tid in art else (0, 0, 32, 32)
        name = os.path.basename(art[tid]) if tid in art else "-"
        lines.append("    { %2d, %2d, %2d, %2d },   /* %3d %s */" % (b[0], b[1], b[2], b[3], tid, name))
    lines.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d trinkets, ids up to %d -> %s" % (len(art), top, OUT))


if __name__ == "__main__":
    main()
