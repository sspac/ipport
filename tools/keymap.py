# -*- coding: utf-8 -*-
"""The hardware keyboard by the PLACE of a key: Linux scan code -> HID usage.

Batch 2, item K2 (01.10.2026). Android gives a key two numbers: getKeyCode(),
which the layout may change (the French and German .kcm files remap letters;
some OEM boards send Esc as BACK), and getScanCode(), the Linux KEY_* number
the kernel made of the HID usage - the place of the key, whatever the layout.
The game reads keys the UIKit way, by HID usage, through its own table
0x945ad4 (HID -> GLFW), and a PC keyboard in GLFW is positional too: WASD on
AZERTY is the same four physical keys. So the port turns the scan code back
into the HID usage, and the layout no longer matters to the game.

The table is Chromium's (ui/events/keycodes/dom/dom_code_data.inc, the USB and
evdev columns - the same pairing a browser uses for KeyboardEvent.code on
Android, where the native code IS the evdev one), kept beside this tool as
tools/dom_code_data.inc. Only page 0x07 (the keyboard page) is taken, and of
it only the usages the GAME knows (0x945ad4 gives -1 for the rest): a key the
game does not read - volume, power, the media keys, the Windows key - stays
the system's, as it does on an iPhone.

Two places differ from the plain inverse, both because of the game's table:
  KEY_ENTER (28)   -> 0x9e: the game throws 0x28 away (-1) and reads Return
                      as 0x9e (GLFW 257, what MENU CONFIRM is bound to);
  KEY_KPENTER (96) -> 0x58: as Chromium has it, noted for the record.

Writes port/app/src/main/java/ru/isaac/port/KeyMap.java and prints the desk
check against the image:  py -3 tools/keymap.py
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, 'tools', 'dom_code_data.inc')
IMAGE = os.path.join(ROOT, 'work', 'isaac.arm64')
OUT = os.path.join(ROOT, 'port', 'app', 'src', 'main', 'java', 'ru', 'isaac', 'port', 'KeyMap.java')

HID_TO_GLFW = 0x945ad4          # int32 per HID usage, -1 unknown
OVERRIDE = {28: 0x9e, 96: 0x58}  # KEY_ENTER, KEY_KPENTER


def chromium_rows():
    rows = []
    rx = re.compile(r'DOM_CODE\(0x([0-9a-f]{6}),\s*0x([0-9a-f]{4}),\s*0x[0-9a-f]{4},\s*0x[0-9a-f]{4},'
                    r'\s*0x[0-9a-f]{4},\s*(NULL|"[^"]*"),\s*(\w+)\)')
    for m in rx.finditer(open(INC, encoding='utf-8').read()):
        usb, evdev, code, name = int(m.group(1), 16), int(m.group(2), 16), m.group(3), m.group(4)
        rows.append((usb, evdev, code.strip('"') if code != 'NULL' else None, name))
    return rows


def game_table():
    d = open(IMAGE, 'rb').read()
    return struct.unpack_from('<256i', d, HID_TO_GLFW)


def main():
    rows = chromium_rows()
    game = game_table()
    table = [0] * 256
    names = {}
    left_out = []
    for usb, evdev, code, name in rows:
        if usb >> 16 != 0x07 or not evdev or evdev >= 256:
            continue
        hid = OVERRIDE.get(evdev, usb & 0xffff)
        if hid > 0xff or game[hid] < 0:
            left_out.append((evdev, usb & 0xffff, code or name))
            continue
        if table[evdev]:
            sys.exit('two usages for scan %d: %#x and %#x' % (evdev, table[evdev], hid))
        table[evdev] = hid
        names[evdev] = code or name
    for evdev, hid in OVERRIDE.items():
        if table[evdev] != hid:
            sys.exit('the override for scan %d did not land (%#x)' % (evdev, table[evdev]))
    keys = sum(1 for h in table if h)
    known = sum(1 for h in table if h and game[h] >= 0)
    reach = {h for h in table if h}
    # 0x00..0x03 are HID's reserved and error codes, 0x82..0x84 the locking keys
    # of old boards and 0x86 the AS/400 keypad's equals: no key sends them
    unreached = [h for h in range(4, 256) if game[h] >= 0 and h not in reach]

    lines = []
    for i in range(0, 256, 8):
        lines.append('        ' + ', '.join('0x%02x' % table[j] for j in range(i, i + 8)) + ',')
    src = '''package ru.isaac.port;

/*
 * GENERATED by tools/keymap.py - do not edit by hand, run the tool.
 *
 * The HID usage of a key's PLACE, by its Linux scan code (KeyEvent.getScanCode)
 * - Chromium's usb/evdev pairing (tools/dom_code_data.inc), keyboard page only,
 * only the usages the game's own table 0x945ad4 knows. 0 means "not a key the
 * game reads": such a key stays the system's. Return is 0x9e, the usage the
 * game reads as Return (it throws 0x28 away). %d keys.
 */
final class KeyMap {
    private KeyMap() { }

    static final short[] HID_OF_SCAN = {
%s
    };

    /* the HID usage of the key at this place, or 0 */
    static int hidOfScan(int scan) {
        return scan > 0 && scan < HID_OF_SCAN.length ? HID_OF_SCAN[scan] : 0;
    }
}
''' % (keys, '\n'.join(lines))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(src)

    print('keymap: %d keys, the game knows %d of them' % (keys, known))
    print('keymap: Enter scan 28 -> %#x -> GLFW %d, KP Enter scan 96 -> %#x -> GLFW %d'
          % (table[28], game[table[28]], table[96], game[table[96]]))
    print('keymap: usages the game knows that no scan code reaches: %s'
          % (' '.join('%#x' % h for h in unreached) or 'none'))
    print('keymap: keyboard-page usages left to the system (the game gives -1): %d, e.g. %s'
          % (len(left_out), ', '.join('%s %d->%#x' % (n, e, h) for e, h, n in left_out[:8])))
    print('written', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
