# -*- coding: utf-8 -*-
"""content_table.h for content.c, generated from the reference model's key table.

    py -3 tools/contentdesk/gen_table.py          writes port/app/src/main/cpp/content_table.h
    py -3 tools/contentdesk/gen_table.py --check  exits 1 when the header is not what the model gives

The key table (tools/content_sim.py T) is the spec; the C side never keeps a
hand copy of it. The port's own stringtable fill (port_additions.py
stringtable_patch, step 5 of the build) goes into the same header.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import content_sim as cs          # noqa: E402
import port_additions             # noqa: E402

OUT = os.path.join(ROOT, "port", "app", "src", "main", "cpp", "content_table.h")


def cstr(s):
    if s is None:
        return "NULL"
    b = s.encode("utf-8") if isinstance(s, str) else s
    out = []
    for c in b:
        if c in (0x22, 0x5C):
            out.append("\\" + chr(c))
        elif 0x20 <= c < 0x7F and c != 0x3F:
            out.append(chr(c))
        else:
            out.append("\\%03o" % c)
    return '"' + "".join(out) + '"'


class Gen:
    def __init__(self):
        self.lines = []
        self.n = 0

    def name(self, what):
        self.n += 1
        return "ct_%s%d" % (what, self.n)

    def strs(self, items):
        nm = self.name("s")
        self.lines.append("static const char *const %s[] = { %s };" % (nm, ", ".join([cstr(x) for x in items] + ["NULL"])))
        return nm

    def rec_array(self, recs):
        """the records of one parent, as a crec_t array ending with a zero entry; its name"""
        body = []
        for r in recs:
            kids = self.rec_array(r.kids) if r.kids else "NULL"
            tags = self.strs(r.tags)
            key = self.strs([a for a, d in r.key])
            keydef = "{ %s }" % ", ".join([cstr(d) for a, d in r.key] + ["NULL"] * (3 - len(r.key)))
            attrs = self.strs(sorted(r.attrs))
            lists = self.strs(sorted(r.lists))
            lkind = cstr("".join("m" if r.lists[a] == "multiset" else "s" for a in sorted(r.lists)))
            refs = self.strs(sorted(r.refs))
            rkind = self.strs([r.refs[a] for a in sorted(r.refs)])
            bnm = "NULL"
            if r.bounds:
                bnm = self.name("b")
                rows = []
                for attr, lo, hi, kind, when in r.bounds:
                    wk, wa, wv = 0, "NULL", "NULL"
                    if when and when[0] == "prefix":
                        wk, wa = "'p'", cstr(when[1])
                    elif when:
                        wk, wa, wv = "'a'", cstr(when[0]), self.strs(when[1])
                    rows.append("{ %s, %dLL, %dLL, %d, %d, '%s', %s, %s, %s }" % (
                        cstr(attr), lo or 0, hi or 0, lo is not None, hi is not None,
                        {"danger": "d", "ignored": "i", "ascii": "a"}[kind], wk, wa, wv))
                rows.append("{ 0 }")
                self.lines.append("static const cbound_t %s[] = {\n    %s\n};" % (bnm, ",\n    ".join(rows)))
            body.append("{ %s, %s, %s, %d, %s, %s, %s, %s, %s, %s, %s, %d, %d }" % (
                tags, key, keydef, len(r.key), attrs, lists, lkind, refs, rkind, kids, bnm, r.add, r.remove))
        body.append("{ 0 }")
        nm = self.name("r")
        self.lines.append("static const crec_t %s[] = {\n    %s\n};" % (nm, ",\n    ".join(body)))
        return nm

    def run(self):
        tables = []
        for fname in sorted(cs.T):
            t = cs.T[fname]
            roots = []
            for root in sorted(t.roots):
                ra, recs = t.roots[root]
                roots.append("{ %s, %s, %s }" % (cstr(root), self.strs(ra.split()), self.rec_array(recs)))
            roots.append("{ 0 }")
            rnm = self.name("root")
            self.lines.append("static const croot_t %s[] = {\n    %s\n};" % (rnm, ",\n    ".join(roots)))
            tables.append("{ %s, 0x%x, %s, %d, %d, %d }" % (cstr(fname), t.loader or 0, rnm, t.fixed, t.read, t.content))
        tables.append("{ 0 }")
        port = port_additions.stringtable_patch()
        out = ["/* generated by tools/contentdesk/gen_table.py from tools/content_sim.py (the key table, T) and",
               " * tools/port_additions.py (the port's stringtable fill) - do not edit by hand, run the script */",
               "#ifndef CONTENT_TABLE_H", "#define CONTENT_TABLE_H", ""]
        out += self.lines
        out.append("")
        out.append("static const ctable_t CT_TABLES[] = {\n    %s\n};" % ",\n    ".join(tables))
        out.append("")
        out.append("/* step 5: the port's own stringtable keys, filled where empty or missing */")
        chunks = [port[i:i + 60] for i in range(0, len(port), 60)]
        out.append("static const char CT_PORT_STRINGTABLE[] =\n    %s;" % "\n    ".join(cstr(c) for c in chunks))
        out.append("#define CT_PORT_STRINGTABLE_LEN %d" % len(port))
        out.append("")
        out.append("#endif")
        return "\n".join(out) + "\n"


def main(argv):
    text = Gen().run()
    if "--check" in argv:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        print("content_table.h", "up to date" if have == text else "DIFFERS - run gen_table.py")
        return 0 if have == text else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT, len(text), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
